"""## 10. Welchova ANOVA – když se rozptyly liší

Welchova ANOVA také testuje **H₀: stejné průměry všech skupin**, ale nevyžaduje stejné rozptyly. Je vhodná zejména tehdy, když se rozptyly nebo počty mezi skupinami liší. U Welchovy ANOVA se pro párová porovnání často používá Games–Howell.

**Úkol:** Spočítejte Welchovu ANOVA a porovnejte její p-hodnotu s klasickou ANOVA.

**Otázky k diskusi:**
1. Co testuje Welchova ANOVA ve srovnání s klasickou?
  - Testuje totožnou nulovou hypotézu ($H_0$: rovnost středních hodnot skupin), ale bez předpokladu shody rozptylů (homoskedasticity). Používá korigované stupně volnosti a vážené průměry podle rozptylů skupin.
2. V jaké situaci bychom jí dali přednost?
  - Když je porušen předpoklad homogenity rozptylů (např. Leveneho test má $p < 0{,}05$), a to zejména v případě, kdy jsou skupiny navíc nevyvážené (mají různé počty pozorování $n$).
3. Řeší Welchova ANOVA závislost měření stejného člověka?
  - Ne, vůbec ne. Welchova ANOVA řeší pouze heteroskedasticitu (nerovnost rozptylů). Stále striktně vyžaduje nezávislá pozorování. Pro závislá měření (stejný člověk opakovaně) je nutné použít Repeated Measures ANOVA nebo smíšené lineární modely (LMM).
"""

