"""### Odstranění odlehlé hodnoty pomocí Z-skore

Většinou používáme pravidlo 3 sigma -> přísnější verze 4 sigma.
"""

# calculate z-score for removing the outlier values
z_scores = stats.zscore(data_DF_outlier)

# thresholding z-score values
# absolutní hodnota z-skóre
abs_z_scores = np.abs(z_scores)

# maska: zachovat řádky, kde ŽÁDNÝ příznak nepřekročí práh (např. 3 sigma)
filtered_entries =  (abs_z_scores < 3).all(axis=1)

# vyfiltrování datasetu bez odlehlých hodnot
data_DF_filtered = data_DF_outlier[filtered_entries]

print(data_DF_filtered)

data_DF_filtered.corr(method="pearson")

